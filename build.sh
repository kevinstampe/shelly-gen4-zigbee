#!/usr/bin/env bash
# Build (and optionally flash) Zigbee firmware for a Shelly Gen4 model.
#   ./build.sh <model> [--webui] [--flash] [--backup NAME] [--port /dev/ttyUSB0]
# models: 1, 1-mini, 1pm, 1pm-mini, 2pm, em-mini
# --webui builds a zip for the stock Shelly web UI (webui/<model>-zigbee-webui.zip)
set -euo pipefail
cd "$(dirname "$0")"

usage() { sed -n 2,5p "$0" | sed 's/^# \{0,1\}//'; exit 1; }

[[ $# -ge 1 ]] || usage
case "$1" in
  1)        model=shelly-1-gen4 ;;
  1-mini)   model=shelly-1-mini-gen4 ;;
  1pm)      model=shelly-1pm-gen4 ;;
  1pm-mini) model=shelly-1pm-mini-gen4 ;;
  2pm)      model=shelly-2pm-gen4 ;;
  em-mini)  model=shelly-em-mini-gen4 ;;
  *)        usage ;;
esac
shift

flash=0; webui=0; backup=""; port=/dev/ttyUSB0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --flash)  flash=1 ;;
    --webui)  webui=1 ;;
    --backup) backup="$2"; shift ;;
    --port)   port="$2"; shift ;;
    *)        usage ;;
  esac
  shift
done

if [[ -z "${VIRTUAL_ENV:-}" && -f ../.venv/bin/activate ]]; then
  source ../.venv/bin/activate
fi
command -v esphome >/dev/null || { echo "esphome not found; install it (pip install esphome) or activate its venv"; exit 1; }

esptool() { uvx esptool --chip esp32c6 --port "$port" --baud 115200 "$@"; }

if [[ $webui -eq 1 ]]; then
  csv=common/shelly-gen4-stock-zigbee.csv
  [[ $model == shelly-em-mini-gen4 ]] && csv=common/shelly-em-mini-gen4-stock-zigbee.csv
  wrapper=".webui-$model.yaml"
  cat > "$wrapper" <<EOF
# Generated by build.sh: stock Shelly flash layout for web UI installs.
substitutions:
  device_name: "$model-zb-web"
packages:
  device: !include $model-zigbee.yaml
esp32:
  partitions: $csv
  framework:
    sdkconfig_options:
      CONFIG_PARTITION_TABLE_OFFSET: "0x10000"
EOF
  esphome compile "$wrapper"
  mkdir -p webui
  (cd webui && python3 ../tools/make-esphome-ota-zip.py --hardware "$model" --version zigbee \
      --build-dir "../.esphome/build/$model-zb-web/build" >/dev/null)
  mv "webui/automatous-io-$model-esphome-vzigbee-ota.zip" "webui/$model-zigbee-webui.zip"
  echo "Built webui/$model-zigbee-webui.zip"
  exit 0
fi

esphome compile "$model-zigbee.yaml"
cp ".esphome/build/$model-zb/build/firmware.factory.bin" "$model-zigbee-factory.bin"
echo "Built $model-zigbee-factory.bin"

if [[ -n "$backup" ]]; then
  info=$(esptool chip-id)
  mac=$(awk '/BASE MAC/ {gsub(":","",$3); print $3; exit}' <<<"$info")
  [[ -n "$mac" ]] || { echo "Could not read MAC; is the device in flash mode?"; exit 1; }
  out="../stock-$model-$backup-$mac.bin"
  esptool read-flash 0x0 ALL "$out"
  esptool verify-flash 0x0 "$out"
  echo "Backup saved to $out"
fi

if [[ $flash -eq 1 ]]; then
  esptool erase-flash
  esptool write-flash 0x0 "$model-zigbee-factory.bin"
  echo "Flashed. Remove the BOOT-GND bridge and power-cycle."
fi
